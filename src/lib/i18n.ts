export function isLanguageCode(value: string | null | undefined): value is LanguageCode {
  return LANGUAGES.some((item) => item.code === value);
}

export function localeFor(language: LanguageCode) {
  return LANGUAGES.find((item) => item.code === language)?.locale ?? "ru-RU";
}

export function tr(language: LanguageCode, key: string, vars?: TranslationVars) {
  const template = translations[language]?.[key] ?? translations.ru[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : match,
  );
}

export function localizedTask(language: LanguageCode, code: string, fallbackTitle: string, fallbackDescription: string) {
  return taskTranslations[language]?.[code] ?? taskTranslations.ru[code] ?? { title: fallbackTitle, description: fallbackDescription };
}

export function localizedAchievement(language: LanguageCode, code: string, fallbackTitle: string, fallbackDescription: string) {
  return achievementTranslations[language]?.[code] ?? achievementTranslations.ru[code] ?? { title: fallbackTitle, description: fallbackDescription };
}
